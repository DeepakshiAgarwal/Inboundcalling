-- CSAT: ratings 4-5 out of all ratings 1-5
WITH f AS (
  SELECT DISTINCT CALL_ID, QUEUE_NAME, FEEDBACK_INPUT,
         COALESCE(TRY_TO_TIMESTAMP_NTZ(CALL_DATE_AND_TIME, 'MM/DD/YY HH12:MI AM'),
                  TRY_TO_TIMESTAMP_NTZ(CALL_DATE_AND_TIME, 'YYYY-MM-DD HH24:MI:SS'))::DATE AS DT
  FROM PROD_DB.AMEYO_MAIL.FEEDBACKREPORT
  WHERE QUEUE_NAME IN ('high_pain_queue', 'low_pain_queue', 'Wiom_Net_Queue'))
SELECT TO_VARCHAR(DT, 'YYYY-MM-DD') AS D, IFF(QUEUE_NAME = 'Wiom_Net_Queue', 'wn', 'svc') AS QG,
       COUNT_IF(FEEDBACK_INPUT IN ('4', '5')) AS POSITIVE,
       COUNT_IF(FEEDBACK_INPUT IN ('1', '2', '3', '4', '5')) AS TOTAL
FROM f WHERE DT >= DATE '{LO}' AND DT <= DATE '{HI}' GROUP BY 1, 2
