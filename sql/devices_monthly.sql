-- Paying = plan still running on the cut-off day; active R15 = plan ended at most 15 days before it
WITH cut AS (
  SELECT TO_VARCHAR(d, 'YYYY-MM') AS YM, GREATEST(d, LEAST(LAST_DAY(d), DATEADD(day, -1, DATE '{HI}'))) AS CD
  FROM (SELECT DATEADD(month, ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1, DATE_TRUNC('month', DATE '{LO}'))::DATE AS d
        FROM TABLE(GENERATOR(ROWCOUNT => 60)))
  WHERE d <= DATE '{HI}'),
e AS (
  SELECT c.YM, c.CD, t.ROUTER_NAS_ID, MAX(DATEADD('minute', 330, t.OTP_EXPIRY_TIME)::DATE) AS X
  FROM PROD_DB.PUBLIC.T_ROUTER_USER_MAPPING t
  JOIN cut c ON DATEADD('minute', 330, t.OTP_ISSUED_TIME)::DATE <= c.CD
  WHERE t.OTP = 'DONE' AND t.DEVICE_LIMIT = 10 AND t.MOBILE > '5999999999'
    AND t.CREATED_BY NOT IN (SELECT LCO_ACCOUNT_ID FROM PROD_DB.PUBLIC.TEST_LCO_ACCOUNT_ID
                             WHERE LCO_ACCOUNT_ID IS NOT NULL)
  GROUP BY 1, 2, 3)
SELECT YM, COUNT_IF(X >= CD) AS PAYING, COUNT_IF(X >= DATEADD(day, -15, CD)) AS ACTIVE FROM e GROUP BY 1
