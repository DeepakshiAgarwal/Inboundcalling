-- Internet Supply Down calls by hour with the caller's partner (latest ticket) and that partner's latest ISP.
-- Partner split is within about 3 % of the original; the ISP split is approximate.
WITH c AS (
  SELECT TO_VARCHAR(CALL_TIME::DATE, 'YYYY-MM-DD') AS D, HOUR(CALL_TIME) AS H, RIGHT(PHONE, 10) AS PH
  FROM PROD_DB.PUBLIC.AMEYO_CALL_DETAILS_REPORT
  WHERE QUEUE_NAME IN ('high_pain_queue', 'low_pain_queue') AND CALL_TYPE = 'inbound.call.dial'
    AND DISPOSITION_CODE = 'Internet Supply Down'
    AND CALL_TIME::DATE >= DATE '{LO}' AND CALL_TIME::DATE <= DATE '{HI}'),
t AS (
  SELECT RIGHT(CUSTOMER_MOBILE, 10) AS PH, CURRENT_PARTNER_NAME AS CSP, TO_VARCHAR(CURRENT_PARTNER_ACCOUNT_ID) AS PID
  FROM PROD_DB.PUBLIC.SERVICE_TICKET_MODEL
  QUALIFY ROW_NUMBER() OVER (PARTITION BY RIGHT(CUSTOMER_MOBILE, 10) ORDER BY TICKET_ADDED_TIME DESC) = 1),
i AS (
  SELECT TO_VARCHAR(PARTNER_ID) AS PID, ISP_NAME FROM PROD_DB.DBT.DIM_CX_PARTNER_LATEST_ISP
  QUALIFY ROW_NUMBER() OVER (PARTITION BY PARTNER_ID ORDER BY ISP_SEEN_DATE DESC, ISP_NAME) = 1)
SELECT c.D, c.H, NULLIF(TRIM(t.CSP), '') AS CSP, NULLIF(TRIM(i.ISP_NAME), '') AS ISP, COUNT(*) AS N
FROM c LEFT JOIN t ON t.PH = c.PH LEFT JOIN i ON i.PID = t.PID GROUP BY 1, 2, 3, 4
