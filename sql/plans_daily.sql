-- Wiom Net plans sold per IST day
SELECT TO_VARCHAR(DATEADD('minute', 330, CREATED_TIME)::DATE, 'YYYY-MM-DD') AS D, COUNT(*) AS PLANS_SOLD
FROM PROD_DB.WIOMNET_CORE_SERVICE_PUBLIC.SECONDARY_SIGNAL_ROUTER_PLAN_INFO
WHERE OTP = 'DONE' AND DATEADD('minute', 330, CREATED_TIME)::DATE >= DATE '{LO}'
  AND DATEADD('minute', 330, CREATED_TIME)::DATE <= DATE '{HI}' GROUP BY 1
